// node --experimental-strip-types scripts/make-seed-sql.ts > supabase/seed.sql
import { GENERICS } from '../src/data/seed.ts';

const q = (v: string | number | null) =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;

const out: string[] = ['-- Generated by scripts/make-seed-sql.ts. Generic foods only (no sample brands).', 'begin;'];

for (const f of GENERICS) {
  out.push(
    `insert into public.foods (slug,name,brand,variant,category,is_generic,kcal,protein,carbs,fat,fibre,sugar,serving_g,serving_label,piece_weight_g,piece_label,raw_to_cooked_factor,source_name,status,confidence) values (` +
      [f.slug, f.name, f.brand, f.variant, f.category].map(q).join(',') + ',true,' +
      [f.kcal, f.protein, f.carbs, f.fat, f.fibre, f.sugar, f.serving_g, f.serving_label, f.piece_weight_g, f.piece_label, f.raw_to_cooked_factor, f.source_name].map(q).join(',') +
      `,'auto_fetched','low') on conflict (slug) do nothing;`,
  );
  for (const a of f.aliases) {
    out.push(`insert into public.aliases (food_id, alias) select id, ${q(a)} from public.foods where slug = ${q(f.slug)};`);
  }
}
out.push('commit;');
console.log(out.join('\n'));
